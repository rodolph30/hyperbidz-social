# Source: Lebanese Code of Civil Procedure (Decree-Law 90/1983), Art. 978, legiliban.ul.edu.lb (re-checked 23 Oct 2026):
#  - if the buyer doesn't deposit the full price within three days of the award decision, the head of the Execution Department sets
#    a new sale session; the notices are published again and name the property, the price of the first award and the person awarded;
#  - if someone at the new session accepts to buy with an increase of one tenth, bringing the full price including the increase or an
#    equivalent bank guarantee, the bidding is reopened on that price;
#  - if no one offers the tenth, the first buyer may, in the same session, deposit his price plus the costs of his delay; otherwise
#    the property is put back to auction immediately, at his risk;
#  - no offer counts at that session unless it comes with its full value or an equivalent bank guarantee.
